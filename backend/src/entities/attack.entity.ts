import { Entity, Column, PrimaryGeneratedColumn, CreateDateColumn, Index } from 'typeorm';
import type { eventContext } from '../event-context';

@Entity()
@Index('IDX_attack_visibility_scope',['alertEligible','targetScope','timestampMs'])
@Index('IDX_attack_actor_event_time',['ip','alertEligible','timestampMs'])
@Index('IDX_attack_actor_processed_time',['ip','alertEligible','lastProcessedMs'])
export class Attack {
  @Column({ type: 'simple-json', nullable: true }) httpContext: import('../http-context').HttpContext;
  @Column({ type: 'simple-json', nullable: true }) aiInvestigation: any;
  @Column({type:'bigint',nullable:true})
  lastProcessedMs: number;
  @Column({ default: false })
  @Index()
  alertEligible: boolean;

  @Column({ nullable: true })
  detectionMode: string;

  @Column({ nullable: true })
  alertPolicyVersion: string;

  @Column({ type: 'simple-json', nullable: true })
  networkContext: ReturnType<typeof eventContext>;

  @Column({ nullable: true })
  @Index()
  targetScope: string;

  @Column({ type: 'int', nullable: true })
  srcPort: number;

  @Column({ type: 'int', nullable: true })
  destPort: number;

  @Column({ nullable: true })
  protocol: string;
  @Column({ nullable: true, unique: true })
  aggregationKey: string;

  @Column({ nullable: true })
  source: string;

  @Column({ nullable: true })
  eventId: string;

  @Column({ type: 'bigint', nullable: true })
  firstSeenMs: number;

  @Column({ type: 'bigint', nullable: true })
  lastSeenMs: number;

  @Column({ type: 'simple-json', nullable: true })
  correlationChain: string[];

  @Column({ type: 'simple-json', nullable: true })
  detectionEvidence: any;

  @Column({ nullable: true })
  killChainPhase: string;

  @Column({ nullable: true })
  ruleId: string;

  @Column({ nullable: true })
  outcome: string;

  @PrimaryGeneratedColumn()
  id: number;

  @Column({ type: 'int', default: 1 })
  hitCount: number;

  @Column()
  timeStr: string;

  @Column()
  ip: string;

  @Column()
  type: string;

  @Column()
  severity: string;

  @Column()
  detail: string;

  @Column({ nullable: true })
  mitigation: string;

  @Column({ nullable: true })
  country: string;

  @Column({ nullable: true })
  clientVersion: string;

  @Column({ nullable: true })
  mitreCode: string;

  @Column({ type: 'float', nullable: true })
  latitude: number;

  @Column({ type: 'float', nullable: true })
  longitude: number;

  @Column({ type: 'int', default: 50 })
  threatScore: number;

  @Column({ default: 'Opened' })
  status: string;

  @Column({ nullable: true })
  sessionId: string;

  // Target honeypot IP and port that was attacked
  @Column({ nullable: true })
  destIp: string;

  @Column({ type: 'int', nullable: true })
  honeypotPort: number;

  @Column({ type: 'bigint', nullable: true })
  @Index()
  timestampMs: number;

  // AI analysis result (Thai language, generated by Gemini or rule-based engine)
  @Column({ type: 'text', nullable: true })
  aiAnalysis: string;

  @Column({ nullable: true })
  assignee: string;

  @Column({ type: 'text', nullable: true })
  notes: string;

  @CreateDateColumn()
  @Index()
  createdAt: Date;
}
